#!/usr/bin/env python3
"""Build Table S6 from saved results (standard library only; no experiments run).

Run from any directory; add --sync-overleaf to update the supplementary copy.
The CSV retains full precision. Times are additive component wall times.
"""

import argparse
from collections import defaultdict
import csv
import json
import math
from pathlib import Path
import re
from statistics import mean, stdev


ROOT = Path(__file__).resolve().parents[3]
LEARNERS = {'lightgbm': 'LightGBM', 'random_forest': 'Random Forest', 'xgboost': 'XGBoost'}
IDS = {2, 13, 29, 55, 63}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_csv(path):
    with path.open(newline='') as handle:
        return list(csv.DictReader(handle))


def build_rows(source, composition):
    protocol = json.loads((source / 'protocol.json').read_text())
    require(protocol['status'] == 'completed' and protocol['completed_results'] == 45,
            'Expected the completed 45-run comparison')
    labels = dict(re.findall(r'^Model (\d+): (.*?) &', composition.read_text(), re.M))
    records = read_csv(source / 'results.csv')
    require(len(records) == 45, 'Expected 45 result rows')
    groups = defaultdict(list)
    for record in records:
        model = int(re.fullmatch(r'dataset(\d+)_.+', record['dataset'])[1])
        require(record['smoke_test'].lower() == 'false', 'Smoke-test result found')
        require(record['condition'] == 'selected_tuned', 'Unexpected pipeline condition')
        require(record['seed'] == str(protocol['configuration']['seed']), 'Fold/learner seed mismatch')
        metric = 'R2' if model == 63 else 'MCC'
        require(record['primary_metric'] == metric and int(record['test_records']) > 0,
                'Expected held-out test performance')
        score = float(record['primary_score'])
        require(math.isfinite(score) and math.isclose(score, float(record['test_' + metric])),
                'Primary score differs from test score')
        minutes = float(record['pipeline_minutes'])
        components = [float(record[key]) for key in
                      ('shared_total_minutes', 'stage_1_total_minutes', 'condition_minutes')]
        require(all(math.isfinite(v) and v >= 0 for v in components)
                and math.isclose(minutes, sum(components)), 'Invalid additive timing')
        groups[model, record['learner']].append(record)
    require(set(groups) == {(model, learner) for model in IDS for learner in LEARNERS},
            'Unexpected dataset/selector coverage')
    summaries = {(r['dataset'], r['learner']): r for r in read_csv(source / 'summary.csv')}
    rows = []
    for model in sorted(IDS):
        for learner in LEARNERS:
            group = groups[model, learner]
            require(len(group) == 3 and {int(r['search_seed']) for r in group}
                    == set(protocol['configuration']['search_seeds']), 'Missing or duplicate repeat')
            scores = [float(r['primary_score']) for r in group]
            times = [float(r['pipeline_minutes']) for r in group]
            row = dict(model_id=model, model_name_tex=labels[str(model)],
                       dataset=group[0]['dataset'], learner=learner,
                       primary_metric=group[0]['primary_metric'], repeats=len(group),
                       primary_mean=mean(scores), primary_sd=stdev(scores),
                       mean_pipeline_minutes=mean(times), sd_pipeline_minutes=stdev(times))
            saved = summaries[row['dataset'], learner]
            for field in ('primary_mean', 'primary_sd', 'mean_pipeline_minutes'):
                require(math.isclose(row[field], float(saved[field]), rel_tol=1e-10, abs_tol=1e-12),
                        f'Saved summary disagrees for {model}/{learner}/{field}')
            rows.append(row)
    return rows


def render(rows):
    lines = [r'% Generated by manuscript/tables/learner_aware/extract_learner_aware.py',
             r'\begingroup', r'\small', r'\setlength{\tabcolsep}{3pt}',
             r'\renewcommand{\arraystretch}{1.15}',
             r'\setlength{\LTleft}{0pt}', r'\setlength{\LTright}{0pt}',
             r'\setlength{\LTcapwidth}{\linewidth}',
             r'\begin{longtable}{@{}',
             r'  >{\raggedright\arraybackslash}p{0.30\linewidth}',
             r'  >{\raggedright\arraybackslash}p{\dimexpr0.20\linewidth-2\tabcolsep\relax}',
             r'  >{\centering\arraybackslash}p{\dimexpr0.10\linewidth-2\tabcolsep\relax}',
             r'  >{\centering\arraybackslash}p{\dimexpr0.22\linewidth-2\tabcolsep\relax}',
             r'  >{\raggedleft\arraybackslash}p{\dimexpr0.18\linewidth-2\tabcolsep\relax}@{}}',
             r'\caption{\textbf{Effect of the Stage 1 learning algorithm on final pipeline performance.} '
             r'Test performance is reported as mean $\pm$ sample standard deviation across three paired search repeats. '
             r'The metric is MCC for classification and predictive $R^2$ for regression; higher values are better. '
             r'Time is the mean additive pipeline time in minutes using 32 allocated CPUs. '
             r'The experimental design and timing scope are described in the Supplementary Notes '
             r'(Automated machine learning).}\label{tab:learner_aware}\\',
             r'\toprule']
    header = (r'\textbf{Model} & \shortstack{\textbf{Stage 1}\\\textbf{learner}} & '
              r'\textbf{Metric} & \shortstack{\textbf{Test performance}\\(mean $\pm$ SD)} & '
              r'\shortstack{\textbf{Pipeline time}\\(min)} \\')
    lines += [header, r'\midrule', r'\endfirsthead', r'\toprule', header,
              r'\midrule', r'\endhead', r'\midrule',
              r'\multicolumn{5}{r}{\textit{Continued on next page}}\\',
              r'\endfoot', r'\bottomrule', r'\endlastfoot']
    previous = None
    for row in rows:
        model = row['model_id']
        if previous is not None and model != previous:
            lines.append(r'\midrule')
        label = f"Model {model}: {row['model_name_tex']}" if model != previous else ''
        metric = r'$R^2$' if row['primary_metric'] == 'R2' else 'MCC'
        score = f"${row['primary_mean']:.4f} \\pm {row['primary_sd']:.4f}$"
        lines.append(f"{label} & {LEARNERS[row['learner']]} & {metric} & {score} & "
                     f"{row['mean_pipeline_minutes']:.2f} " + r'\\')
        previous = model
    return '\n'.join(lines + [r'\end{longtable}', r'\endgroup', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'manuscript/experiments/results/learner_aware')
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--sync-overleaf', action='store_true')
    args = parser.parse_args()
    rows = build_rows(args.source, ROOT / 'manuscript/tables/composition/datasets.tex')
    table = render(rows)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    with (args.output_dir / 'learner_aware.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (args.output_dir / 'learner_aware.tex').write_text(table)
    if args.sync_overleaf:
        target = ROOT / 'manuscript/revision/overleaf/oup-authoring-template/supplementary/tables/learner_aware.tex'
        target.write_text(table)
    print(f'Validated 45 runs; wrote {len(rows)} table rows to {args.output_dir}')


if __name__ == '__main__':
    main()
